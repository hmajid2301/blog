# Generates data/pixel.toml: rows of palette chars, outline ('x' = currentColor) baked in.
import sys
def outline(rows):
    H=len(rows); W=max(map(len,rows)); rows=[r.ljust(W,'.') for r in rows]
    f=lambda x,y: 0<=y<H and 0<=x<W and rows[y][x]!='.'
    out=[]
    for y in range(-1,H+1):
        line=''
        for x in range(-1,W+1):
            if f(x,y): line+=rows[y][x]
            elif f(x+1,y) or f(x-1,y) or f(x,y+1) or f(x,y-1): line+='x'
            else: line+='.'
        out.append(line)
    return out
